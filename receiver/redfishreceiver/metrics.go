package redfishreceiver

import "go.opentelemetry.io/collector/pdata/pcommon"

func (s *redfishScraper) scrapeComputerSystem(ts pcommon.Timestamp, baseUrl string, compSys *ComputerSystem) {
	s.mb.RecordSystemPowerstateDataPoint(ts,
		powerStateToMetric(compSys.PowerState),
		baseUrl,
		compSys.Id,
		compSys.AssetTag,
		compSys.BiosVersion,
		compSys.HostName,
		compSys.Model,
		compSys.Name,
		compSys.Manufacturer,
		compSys.SerialNumber,
		compSys.SKU,
		compSys.SystemType,
	)
	s.mb.RecordSystemStatusHealthDataPoint(
		ts,
		statusHealthToMetric(compSys.Status.Health),
		baseUrl,
		compSys.Id,
		compSys.AssetTag,
		compSys.BiosVersion,
		compSys.HostName,
		compSys.Model,
		compSys.Name,
		compSys.Manufacturer,
		compSys.SerialNumber,
		compSys.SKU,
		compSys.SystemType,
	)
	s.mb.RecordSystemStatusStateDataPoint(
		ts,
		statusStateToMetric(compSys.Status.State),
		baseUrl,
		compSys.Id,
		compSys.AssetTag,
		compSys.BiosVersion,
		compSys.HostName,
		compSys.Model,
		compSys.Name,
		compSys.Manufacturer,
		compSys.SerialNumber,
		compSys.SKU,
		compSys.SystemType,
	)
}

