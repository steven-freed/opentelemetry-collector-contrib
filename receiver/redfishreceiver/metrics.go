func (s *redfishScraper) scrapeFans(ts pcommon.Timestamp, hostName, baseUrl, chassisId string, fans []Fan) {
	for _, fan := range fans {
		s.mb.RecordFanReadingDataPoint(
			ts,
			*fan.Reading,
			hostName,
			baseUrl,
			chassisId,
			fan.Name,
		)
		s.mb.RecordFanStatusHealthDataPoint(
			ts,
			statusHealthToMetric(fan.Status.Health),
			hostName,
			baseUrl,
			chassisId,
			fan.Name,
		)
		s.mb.RecordFanStatusStateDataPoint(
			ts,
			statusStateToMetric(fan.Status.State),
			hostName,
			baseUrl,
			chassisId,
			fan.Name,
		)
	}
}

func (s *redfishScraper) scrapeTemperatures(ts pcommon.Timestamp, hostName, baseUrl, chassisId string, temps []Temperature) {
	for _, temp := range temps {
		s.mb.RecordTemperatureReadingDataPoint(
			ts,
			int64(*temp.ReadingCelsius),
			hostName,
			baseUrl,
			chassisId,
			temp.Name,
		)
		s.mb.RecordTemperatureStatusHealthDataPoint(
			ts,
			statusHealthToMetric(temp.Status.Health),
			hostName,
			baseUrl,
			chassisId,
			temp.Name,
		)
		s.mb.RecordTemperatureStatusStateDataPoint(
			ts,
			statusStateToMetric(temp.Status.State),
			hostName,
			baseUrl,
			chassisId,
			temp.Name,
		)
	}
}
